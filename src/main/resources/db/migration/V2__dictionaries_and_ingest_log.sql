-- Le righe grezze usano numeri piccoli (satellite, versione, paese) invece di testi: la tabella
-- hotspot_raw (V3) pesa circa un terzo. Qui si decodificano.

-- I satelliti. L'id coincide con la posizione nell'enum Java org.firecal.domain.Satellite + 1:
-- un test di integrazione verifica che tabella e codice restino allineati.
CREATE TABLE satellite (
    id        smallint PRIMARY KEY,
    code      text     NOT NULL UNIQUE,   -- nome nell'enum Java (TERRA, AQUA, SNPP, NOAA20, NOAA21)
    csv_label text     NOT NULL UNIQUE,   -- valore della colonna "satellite" nei CSV FIRMS
    sensor    text     NOT NULL CHECK (sensor IN ('MODIS', 'VIIRS')),
    role      text     NOT NULL CHECK (role IN ('REFERENCE', 'CALIBRATED')),
    first_date date    NOT NULL,          -- primo giorno con dati (misurato sui CSV o dichiarato da FIRMS)
    last_date  date,                      -- NULL = ancora attivo
    note      text
);

