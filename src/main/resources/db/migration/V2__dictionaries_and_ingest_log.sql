-- Registro dei caricamenti: un record per file CSV. L'archivio dei CSV resta FUORI dal database
-- (fonte di verita'); qui si tiene il percorso relativo e l'hash per dimostrare cosa e' stato letto.
CREATE TABLE ingest_run (
    id            integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source        text        NOT NULL,   -- cartella dell'archivio: modis, viirs-snpp, viirs-jpss1, ...
    file_path     text        NOT NULL,   -- relativo alla radice dell'archivio, es. modis/2019/modis_2019_Argentina.csv
    file_sha256   text        NOT NULL,
    country_id    smallint    REFERENCES country (id),
    data_year     smallint,
    rows_read     bigint      NOT NULL DEFAULT 0,
    rows_inserted bigint      NOT NULL DEFAULT 0,
    rows_rejected bigint      NOT NULL DEFAULT 0,
    status        text        NOT NULL CHECK (status IN ('RUNNING', 'OK', 'FAILED')),
    started_at    timestamptz NOT NULL DEFAULT now(),
    finished_at   timestamptz,
    error         text
);

-- Idempotenza a livello di file: un file puo' risultare caricato (OK) una sola volta.
CREATE UNIQUE INDEX ingest_run_one_ok_per_file ON ingest_run (file_path) WHERE status = 'OK';

-- Righe scartate e il motivo (coordinate fuori scala, data illeggibile, confidenza sconosciuta...).
CREATE TABLE ingest_reject (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ingest_run_id integer NOT NULL REFERENCES ingest_run (id) ON DELETE CASCADE,
    line_no       bigint  NOT NULL,
    reason        text    NOT NULL,
    raw_line      text    NOT NULL
);
CREATE INDEX ingest_reject_run ON ingest_reject (ingest_run_id);
