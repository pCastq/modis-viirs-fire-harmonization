-- I paesi dei file FIRMS (un punto sta in un solo paese: nessun duplicato fra file). in_scope = perimetro
-- della fase 1 (Sud America e Italia). Gli altri paesi si aggiungono quando servono.
CREATE TABLE country (
    id       smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     text    NOT NULL UNIQUE,     -- come nei nomi dei file FIRMS (con underscore)
    in_scope boolean NOT NULL DEFAULT false
