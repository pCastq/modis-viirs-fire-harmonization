-- Versione del prodotto FIRMS (colonna "version"). NON distingue SP da NRT nei file standard:
-- per questo hotspot_raw ha un campo "source" a parte. Il caricamento aggiunge le versioni nuove (per esempio 6.1NRT).
CREATE TABLE product_version (
    id      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version text     NOT NULL UNIQUE,
    sensor  text     NOT NULL CHECK (sensor IN ('MODIS', 'VIIRS')),
    note    text
);

